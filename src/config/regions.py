def get_districts_for_city(city: str) -> list[str]:
    """시/도 이름을 넣으면 해당 하위 지역 목록을 반환합니다."""
    return REGIONS.get(city, [])


def get_city_for_district(district: str, fallback: str = "미상") -> str:
    """지역명을 넣으면 소속 시/도를 반환합니다. 중복 지역명은 첫 번째 매핑을 반환합니다."""
    return DISTRICT_CITY_MAP.get(district, fallback)


def get_all_city_district_pairs() -> list[tuple[str, str]]:
    """전국 (시/도, 구/시/군) 쌍 전체를 반환합니다."""
    return [
        (city, district)
        for city, districts in REGIONS.items()
        for district in districts
    ]
