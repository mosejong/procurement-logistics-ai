def _lookup_signgu_cd(city: str, district: str) -> str | None:
    """(city, district) 조합으로 시군구코드를 반환. 없으면 None."""
    if city in API_UNSUPPORTED_CITIES:
        return None
    code = CITY_DISTRICT_SIGNGU_CD.get((city, district))
    if code and code not in AGGREGATE_CITY_CODES:
        return code
    return None


def _fetch_page(signgu_cd: str, page: int, num_rows: int = 1000) -> dict:
    r = requests.get(
        BASE_URL,
        params={
            "serviceKey": STORE_API_KEY,
            "divId": "signguCd",
            "key": signgu_cd,
            "pageNo": page,
            "numOfRows": num_rows,
            "type": "json",
        },
        timeout=30,
    )
    r.raise_for_status()
    return r.json()


def fetch_store_counts(district: str, city: str = "", max_pages: int = 50) -> pd.DataFrame:
    """
    시군구명으로 소상공인 업종별 점포 수를 반환합니다.

    Args:
        district: 시군구 이름 (예: "강남구", "수원시 장안구")
        city: 시/도 이름 (예: "서울특별시"). 동명이구 구분을 위해 필수 권장.

    Returns:
        DataFrame [district, inds_lv1_cd, inds_lv1_nm, store_count]
    """
    signgu_cd = _lookup_signgu_cd(city, district) if city else None
    if not signgu_cd:
        # city 없이 district만으로 서울 기본 조회 (하위 호환)
        for (c, d), code in CITY_DISTRICT_SIGNGU_CD.items():
            if d == district:
                signgu_cd = code
                break
    if not signgu_cd:
        logger.warning("시군구코드 없음: %s %s", city, district)
        return pd.DataFrame()

    all_items: list[dict] = []
    page = 1

    while page <= max_pages:
        try:
            data = _fetch_page(signgu_cd, page)
        except Exception as e:
            logger.error("store API 오류 (%s %s, page=%d): %s", city, district, page, e)
            break

        rc = data.get("header", {}).get("resultCode", "")
        if rc != "00":
            break

        body = data.get("body", {})
        items = body.get("items", [])
        if not items:
            break

        all_items.extend(items)

        total = int(body.get("totalCount", 0))
        if len(all_items) >= total:
            break

        page += 1
        time.sleep(0.3)

    if not all_items:
        return pd.DataFrame()

    df = pd.DataFrame(all_items)
    if "indsLclsCd" not in df.columns:
        return pd.DataFrame()

    counts = (
        df.groupby(["indsLclsCd", "indsLclsNm"], dropna=False)
        .size()
        .reset_index(name="store_count")
        .rename(columns={"indsLclsCd": "inds_lv1_cd", "indsLclsNm": "inds_lv1_nm"})
    )
    counts.insert(0, "city", city)
    counts.insert(1, "district", district)
    return counts


def validate_signgu_codes(
    targets: list[tuple[str, str]] | None = None,
    sample_per_sido: int = 0,
) -> dict[tuple[str, str], bool]:
    """
    CITY_DISTRICT_SIGNGU_CD 코드를 실제 API 호출로 검증합니다.

    Args:
        targets: [(city, district), ...] 검증 대상. None이면 전체.
        sample_per_sido: 0이면 전체, N이면 시/도당 N개만 검증 (빠른 검증용).

    Returns:
        {(city, district): True/False}
    """
    if targets is None:
        all_keys = list(CITY_DISTRICT_SIGNGU_CD.keys())
        if sample_per_sido > 0:
            from itertools import groupby
            targets = []
            for city, group in groupby(all_keys, key=lambda x: x[0]):
                targets.extend(list(group)[:sample_per_sido])
        else:
            targets = all_keys

    results: dict[tuple[str, str], bool] = {}
    for city, district in targets:
        cd = _lookup_signgu_cd(city, district)
        if not cd:
            results[(city, district)] = False
            logger.warning("[SKIP] %s %s - 코드 없음", city, district)
            continue
        try:
            data = _fetch_page(cd, page=1, num_rows=1)
            rc = data.get("header", {}).get("resultCode", "")
            valid = rc == "00"
        except Exception:
            valid = False
        results[(city, district)] = valid
        status = "OK  " if valid else "FAIL"
        logger.info("[%s] %s %s (%s)", status, city, district, cd)
        time.sleep(0.2)
    return results


def run_validation_report(sample_per_sido: int = 2) -> None:
    """
    시/도당 N개 샘플로 코드 검증 후 결과를 출력합니다.
    전체 검증 전 빠른 사전 점검용.
    """
    import logging
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    print(f"검증 시작 (시/도당 {sample_per_sido}개 샘플) ...")
    results = validate_signgu_codes(sample_per_sido=sample_per_sido)

    ok = [k for k, v in results.items() if v]
    fail = [k for k, v in results.items() if not v]

    print(f"\n[결과] OK: {len(ok)} / FAIL: {len(fail)} / 총: {len(results)}")
    if fail:
        print("\n[FAIL 목록]")
        for city, district in fail:
            cd = _lookup_signgu_cd(city, district) or "?"
            print(f"  {city} {district} ({cd})")
